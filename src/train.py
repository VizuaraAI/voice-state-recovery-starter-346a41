"""Train the interruption typology classifier.

    python -m src.train --config configs/default.yaml

Training data is generated by the same injection protocol used at evaluation
time, with a different seed and a disjoint dialogue pool. That is convenient,
and it is also the first thing a reviewer will question, so the script prints
the train/test seed pair and you should report it in the paper. Moving to
human-labelled interruption types is the Week 5 upgrade.
"""

from __future__ import annotations

import argparse
import json
import os

from .data import load_dialogues
from .eval import load_config
from .interruptions import build_suite


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default="configs/default.yaml")
    ap.add_argument("--out", default=None, help="override typology_checkpoint")
    args = ap.parse_args()

    import joblib
    from sklearn.metrics import classification_report
    from sklearn.model_selection import train_test_split

    from .typology import LearnedTypologyClassifier

    cfg = load_config(args.config)
    train_cfg = json.loads(json.dumps(cfg))
    train_cfg["run"]["seed"] = cfg["run"]["seed"] + 1000
    train_cfg["interruptions"]["per_type_count"] = max(
        120, int(cfg["interruptions"]["per_type_count"]) * 3
    )

    dialogues = load_dialogues(train_cfg)
    cases = build_suite(dialogues, train_cfg)
    texts = [c.user_utterance for c in cases]
    labels = [c.event_type for c in cases]
    print(f"{len(texts)} training utterances over {len(set(labels))} event types")
    print(f"eval seed {cfg['run']['seed']}, train seed {train_cfg['run']['seed']}")

    x_tr, x_te, y_tr, y_te = train_test_split(
        texts, labels, test_size=0.2, random_state=cfg["run"]["seed"], stratify=labels
    )

    pipeline = LearnedTypologyClassifier.build()
    pipeline.fit(x_tr, y_tr)
    print(classification_report(y_te, pipeline.predict(x_te), zero_division=0))

    out = args.out or cfg["restate"]["typology_checkpoint"]
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    joblib.dump(pipeline, out)
    print(f"wrote {out}")
    print("Set restate.typology_model: learned in your config to use it.")


if __name__ == "__main__":
    main()
